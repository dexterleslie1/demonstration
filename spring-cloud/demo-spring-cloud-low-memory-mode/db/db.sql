    CREATE TEMPORARY TABLE tmp_bpkc_seq (n INT NOT NULL PRIMARY KEY);
    INSERT INTO tmp_bpkc_seq
    SELECT d0.n + d1.n * 10 + d2.n * 100
    FROM tmp_bpkc_digit d0
    CROSS JOIN tmp_bpkc_digit d1
    CROSS JOIN tmp_bpkc_digit d2;

